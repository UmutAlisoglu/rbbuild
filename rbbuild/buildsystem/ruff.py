import shlex
import subprocess
import sys
import tomllib

from pathlib import Path
from typing import List, Optional

import tomlkit

from packaging.specifiers import InvalidSpecifier, SpecifierSet
from packaging.version import Version

from rbbuild.core.paths import Paths
from rbbuild.librbb.term import term


# Oldest Python version ruff accepts as target-version
_MIN_TARGET_VERSION = (3, 7)


def _command_line(argv: List[str]) -> str:
    return subprocess.list2cmdline(argv) if sys.platform == 'win32' else shlex.join(argv)


class Ruff:
    def __init__(
        self,
        paths: Paths,
        profile_ruff_config: Optional[str] = None,
    ):
        self.paths = paths
        self.profile_ruff_config = Path(profile_ruff_config) if profile_ruff_config else None


    @property
    def available(self) -> bool:
        return any(
            (self.paths.source / name).exists()
            for name in ('pyproject.toml', 'ruff.toml', '.ruff.toml')
        )


    # Settings of the project's ruff configuration in the order ruff prefers
    # its files. Empty if the project does not configure ruff.
    def _project_settings(self) -> dict:
        for name in ('.ruff.toml', 'ruff.toml'):
            toml = self.paths.source / name
            if toml.is_file():
                with open(toml, 'rb') as fd:
                    return tomllib.load(fd)

        pyproject = self.paths.source / 'pyproject.toml'
        if pyproject.is_file():
            with open(pyproject, 'rb') as fd:
                return tomllib.load(fd).get('tool', {}).get('ruff', {})

        return {}


    # Ruff does not infer target-version from requires-python if a
    # configuration file is passed with --config.
    def _requires_python_target(self) -> Optional[str]:
        pyproject = self.paths.source / 'pyproject.toml'
        if not pyproject.is_file():
            return None

        with open(pyproject, 'rb') as fd:
            requires_python = tomllib.load(fd).get('project', {}).get('requires-python')
        if not requires_python:
            return None

        try:
            specifiers = SpecifierSet(requires_python)
        except InvalidSpecifier:
            return None

        lower_bounds = []
        for spec in specifiers:
            if spec.operator in ('>=', '~=', '=='):
                release = Version(spec.version.removesuffix('.*')).release
                lower_bounds.append((release[0], release[1] if len(release) > 1 else 0))
        if not lower_bounds or max(lower_bounds) < _MIN_TARGET_VERSION:
            return None

        major, minor = max(lower_bounds)
        return f'py{major}{minor}'


    def _generate_config(self, project_settings: dict) -> Path:
        config = self.paths.build / 'ruff.toml'
        config.parent.mkdir(parents=True, exist_ok=True)
        header = '# Generated by rbbuild --sca. Do not edit.\n'
        config.write_text(
            header + tomlkit.dumps({'extend': str(self.profile_ruff_config), **project_settings}),
            encoding='utf-8',
        )
        return config


    # Arguments to select the ruff configuration:
    # - no profile configuration: none (ruff discovers the project config)
    # - project config uses extend: none (the profile config is not applied)
    # - project does not configure ruff: the profile config is used as-is
    # - otherwise: generated obj/<tcid>/ruff.toml extending the profile config
    def config_arguments(self) -> List[str]:
        if not self.profile_ruff_config:
            return []

        project_settings = self._project_settings()
        if 'extend' in project_settings:
            term.info('ruff', 'Profile configuration ignored: project configuration uses "extend"')
            return []

        if project_settings:
            config = self._generate_config(project_settings)
        else:
            config = self.profile_ruff_config
        term.debug('ruff config', str(config))
        argv = ['--config', str(config)]

        with open(self.profile_ruff_config, 'rb') as fd:
            profile_settings = tomllib.load(fd)
        if 'target-version' not in project_settings and 'target-version' not in profile_settings:
            target = self._requires_python_target()
            if target:
                argv.extend(['--config', f"target-version = '{target}'"])

        return argv


    def static_code_analysis(self):
        argv = [
            sys.executable, '-m', 'ruff', 'check',
            *self.config_arguments(),
            '--extend-exclude', str(self.paths.build_root),
            '--extend-exclude', str(self.paths.staging_root),
        ]
        term.info(f'Executing command: {term.cyan(_command_line(argv))}')
        proc = subprocess.run(argv, cwd=self.paths.source)
        if proc.returncode == 1:
            # ruff's own --fix hint does not include the configuration of rbbuild
            term.info(
                'ruff reported findings. To apply the available fixes with the '
                f'configuration of rbbuild, run:\n  {term.cyan(_command_line([*argv, "--fix"]))}')
        if proc.returncode != 0:
            raise RuntimeError(f'ruff failed with error code {proc.returncode}')
